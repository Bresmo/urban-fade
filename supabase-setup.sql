create table if not exists public.reservations (
    id bigint generated by default as identity primary key,
    customer_name text not null check (char_length(trim(customer_name)) between 1 and 100),
    phone text not null check (char_length(trim(phone)) between 7 and 25),
    service text not null check (char_length(trim(service)) between 1 and 120),
    appointment_date date not null,
    appointment_time text not null check (appointment_time in (
        '09:00', '09:50', '10:40', '11:30', '12:20', '14:00',
        '14:50', '15:40', '16:30', '17:20', '18:10', '19:00'
    )),
    status text not null default 'pending' check (status in ('pending', 'completed')),
    completed_at timestamptz,
    created_at timestamptz not null default now(),
    constraint reservations_unique_appointment unique (appointment_date, appointment_time),
    constraint reservations_closed_tuesday check (extract(dow from appointment_date) <> 2),
    constraint reservations_completion_timestamp check (
        (status = 'completed' and completed_at is not null)
        or (status = 'pending' and completed_at is null)
    )
);

alter table public.reservations enable row level security;

revoke all on public.reservations from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant insert (customer_name, phone, service, appointment_date, appointment_time)
    on public.reservations to anon;
grant select (appointment_date, appointment_time)
    on public.reservations to anon;
grant select on public.reservations to authenticated;
grant update (status, completed_at) on public.reservations to authenticated;
grant usage, select on sequence public.reservations_id_seq to anon, authenticated;

drop policy if exists "Public can see booked time slots" on public.reservations;
create policy "Public can see booked time slots"
    on public.reservations for select to anon
    using (appointment_date >= (now() at time zone 'America/Guayaquil')::date);

drop policy if exists "Public can create valid reservations" on public.reservations;
create policy "Public can create valid reservations"
    on public.reservations for insert to anon
    with check (
        status = 'pending'
        and completed_at is null
        and appointment_date >= (now() at time zone 'America/Guayaquil')::date
    );

drop policy if exists "Signed-in admins can view reservations" on public.reservations;
create policy "Signed-in admins can view reservations"
    on public.reservations for select to authenticated
    using (true);

drop policy if exists "Signed-in admins can update reservation status" on public.reservations;
create policy "Signed-in admins can update reservation status"
    on public.reservations for update to authenticated
    using (true)
    with check (
        (status = 'pending' and completed_at is null)
        or (status = 'completed' and completed_at is not null)
    );
